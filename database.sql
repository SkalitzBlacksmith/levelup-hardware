CREATE DATABASE IF NOT EXISTS levelup_hardware CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE levelup_hardware;

CREATE TABLE IF NOT EXISTS contactberichten (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    naam VARCHAR(80) NOT NULL,
    email VARCHAR(254) NOT NULL,
    onderwerp VARCHAR(100) NOT NULL,
    bericht TEXT NOT NULL,
    aangemaakt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS nieuwsbrief (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    naam VARCHAR(80) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    aangemaakt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS bestellingen (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    naam VARCHAR(80) NOT NULL,
    email VARCHAR(254) NOT NULL,
    producten TEXT NOT NULL,
    totaal DECIMAL(10,2) NOT NULL,
    aangemaakt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
